def test_fetch_issue_network_failure():
    with patch("requests.get", side_effect=requests.RequestException("connection error")):
        fetch_issue.clear()
        with pytest.raises(UserFacingError) as exc_info:
            fetch_issue("owner", "repo", 13)
        assert "Could not reach GitHub" in str(exc_info.value)


def test_check_cooldown():
    st.session_state["last_request"] = time.time()
    wait = check_cooldown()
    assert 0 < wait <= 16

    st.session_state["last_request"] = time.time() - 20
    assert check_cooldown() == 0


def test_within_daily_cap(monkeypatch):
    monkeypatch.setattr("app.DAILY_PLAN_CAP", 3)
    state = daily_counter()
    with state["lock"]:
        state["day"] = None
        state["count"] = 0

    assert within_daily_cap() is True
    assert within_daily_cap() is True
    assert within_daily_cap() is True
    assert within_daily_cap() is False


def test_build_plan_success():
    mock_client = MagicMock()
