def test_fetch_issue_404():
    mock_resp = MagicMock()
    mock_resp.status_code = 404
    with patch("requests.get", return_value=mock_resp):
        fetch_issue.clear()
        with pytest.raises(UserFacingError) as exc_info:
            fetch_issue("owner", "repo", 999)
        assert "That issue was not found" in str(exc_info.value)


def test_fetch_issue_pull_request_rejected():
    mock_resp = MagicMock()
    mock_resp.status_code = 200
    mock_resp.json.return_value = {
        "title": "PR Title",
        "body": "PR Body",
        "state": "open",
        "pull_request": {"url": "https://..."},
    }
    with patch("requests.get", return_value=mock_resp):
        fetch_issue.clear()
        with pytest.raises(UserFacingError) as exc_info:
            fetch_issue("owner", "repo", 55)
        assert "That link is a pull request" in str(exc_info.value)


