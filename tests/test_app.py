def test_fetch_issue_success(monkeypatch):
    monkeypatch.delenv("GITHUB_TOKEN", raising=False)
    mock_resp = MagicMock()
    mock_resp.status_code = 200
    mock_resp.json.return_value = {
        "title": "A bug title",
        "body": "A bug description",
        "state": "open",
    }
    with patch("requests.get", return_value=mock_resp) as mock_get:
        # fetch_issue has @st.cache_data, call the underlying function or clear cache
        fetch_issue.clear()
        title, body, state = fetch_issue("owner", "repo", 42)
        assert title == "A bug title"
        assert body == "A bug description"
        assert state == "open"

        mock_get.assert_called_once()
        args, kwargs = mock_get.call_args
        assert args[0] == "https://api.github.com/repos/owner/repo/issues/42"
        assert kwargs["allow_redirects"] is False
        assert kwargs["timeout"] == 10
        assert "Authorization" not in kwargs["headers"]


